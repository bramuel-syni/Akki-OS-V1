import hashlib
import json as _json
from pathlib import Path


LIFT_MANIFEST_PATH = Path(__file__).parent.parent.parent / ".." / "docs" / "lift_manifest.json"
MANIFEST_MD_PATH = Path(__file__).parent.parent.parent / ".." / "docs" / "mandates" / "MANIFEST.md"
RULE2_ACCOUNTING_PATH = Path(__file__).parent.parent.parent / ".." / "docs" / "rule2_accounting.json"


def _sha256_of_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _live_source_spec_sha256s() -> List[SourceSpecFingerprint]:
    """Live-computed SHA-256s of every .md file at docs/mandates/ except
    MANIFEST.md itself and phase_source_requirements.yaml. Returns the
    sorted list."""
    mandates_dir = MANIFEST_MD_PATH.parent
    fingerprints: List[SourceSpecFingerprint] = []
    for p in sorted(mandates_dir.glob("*.md")):
        if p.name == "MANIFEST.md":
            continue
        fingerprints.append(SourceSpecFingerprint(
            filename=p.name, sha256=_sha256_of_file(p),
        ))
    return fingerprints


def _load_rule2_accounting() -> Dict[str, Rule2Accounting]:
    if not RULE2_ACCOUNTING_PATH.exists():
        return {}
    data = _json.loads(RULE2_ACCOUNTING_PATH.read_text(encoding="utf-8"))
    return {
        phase: Rule2Accounting(**payload)
        for phase, payload in data.items()
        if not phase.startswith("_")  # skip metadata keys like `_note`
    }


def read_lift_manifest_envelope() -> LiftManifestEnvelope:
    """Read `docs/lift_manifest.json` fresh from disk on every call.

    Never serves stale. Freshness guaranteed by direct file read.
    Zero database writes.
    """
    payload = _json.loads(LIFT_MANIFEST_PATH.read_text(encoding="utf-8"))
    return LiftManifestEnvelope(
        manifest_version=payload["manifest_version"],
        manifest_semantics=payload["manifest_semantics"],
        generated_at=payload["generated_at"],
        generated_by=payload["generated_by"],
        substrate_state=payload["substrate_state"],
        substrate_settled_at=payload.get("substrate_settled_at"),
        entries=[LiftEntry(**e) for e in payload["entries"]],
        source_specs=_live_source_spec_sha256s(),
        phase_accounting=_load_rule2_accounting(),
    )
